/* HarmOS Commerce Studio — local storefront + dropshipping kit generator.
 *
 * Writes draft files only. It does not create a live Shopify/Stripe store, charge
 * cards, or contact suppliers. Generated copy is a starting draft: no fake reviews,
 * no fake scarcity, no counterfeit claims.
 */

export interface StoreSpec {
  brand: string;
  niche: string;
  tone: 'plain' | 'warm' | 'technical';
  products: number;
  theme: 'obsidian' | 'sand' | 'grove';
  marginPct: number;
}

export interface StoreFile { path: string; content: string; }

export interface GeneratedProduct {
  sku: string;
  name: string;
  price: number;
  cost: number;
  leadDays: number;
  blurb: string;
}

const THEME: Record<StoreSpec['theme'], { bg: string; ink: string; accent: string; card: string }> = {
  obsidian: { bg: '#0c0f14', ink: '#e7e5e4', accent: '#22d3ee', card: '#161b22' },
  sand: { bg: '#f6f1e7', ink: '#1c1917', accent: '#9a3412', card: '#fffaf3' },
  grove: { bg: '#f3f6f1', ink: '#14221b', accent: '#3f6212', card: '#ffffff' },
};

function slugify(s: string): string {
  const slug = s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40);
  return slug || 'store';
}

function productsFor(spec: StoreSpec): GeneratedProduct[] {
  const niche = spec.niche.trim() || 'everyday goods';
  const stems = [
    ['Field Kit', 'A starter bundle for people who actually use the thing.'],
    ['Daily', 'The one you reorder. Specified plainly, no invented awards.'],
    ['Travel', 'Sized to pack. Lead time is the supplier\'s, not a marketing number.'],
    ['Studio', 'For repeat use. Replace this blurb with a real spec sheet.'],
    ['Refill', 'Consumable. Only list it if a supplier can ship it.'],
    ['Care', 'Maintenance item. State materials honestly.'],
    ['Pair', 'Sold as a set. Do not imply a discount you will not honor.'],
    ['Archive', 'Limited only if you truly have finite stock. Otherwise delete the word limited.'],
  ];
  const n = Math.max(1, Math.min(8, spec.products));
  const out: GeneratedProduct[] = [];
  for (let i = 0; i < n; i++) {
    const [stem, blurb] = stems[i % stems.length];
    const cost = 12 + i * 7;
    const price = Math.round(cost * (1 + spec.marginPct / 100) * 100) / 100;
    out.push({
      sku: `${slugify(spec.brand).slice(0, 6).toUpperCase() || 'HARM'}-${String(i + 1).padStart(3, '0')}`,
      name: `${niche} ${stem}`.replace(/\s+/g, ' '),
      price, cost, leadDays: 5 + (i % 4) * 3,
      blurb,
    });
  }
  return out;
}

function page(spec: StoreSpec, title: string, body: string): string {
  const t = THEME[spec.theme];
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${escapeHtml(title)} · ${escapeHtml(spec.brand)}</title>
<style>
  :root { color-scheme: ${spec.theme === 'obsidian' ? 'dark' : 'light'}; }
  body { margin:0; font: 16px/1.5 Georgia, "Iowan Old Style", serif; background:${t.bg}; color:${t.ink}; }
  header, main, footer { max-width: 880px; margin: 0 auto; padding: 28px 20px; }
  a { color: ${t.accent}; }
  nav a { margin-right: 14px; text-decoration: none; font: 13px/1 ui-sans-serif, system-ui, sans-serif; letter-spacing: .04em; text-transform: uppercase; }
  .card { background:${t.card}; border: 1px solid ${t.accent}33; border-radius: 14px; padding: 16px 18px; margin: 12px 0; }
  .price { font: 600 18px/1 ui-sans-serif, system-ui, sans-serif; }
  .note { font: 13px/1.45 ui-sans-serif, system-ui, sans-serif; opacity: .75; }
  h1 { font-weight: 500; letter-spacing: -0.03em; }
</style></head><body>
<header><nav><a href="index.html">Shop</a><a href="product.html">Product</a><a href="policies.html">Policies</a><a href="dropship.html">Fulfillment</a></nav>
<p class="note">${escapeHtml(spec.brand)} · draft storefront generated by HarmOS · not a live checkout</p></header>
<main>${body}</main>
<footer class="note">No payment processor is connected. Do not publish fake reviews or countdown timers you cannot honor.</footer>
</body></html>`;
}

function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!));
}

export function generateStore(spec: StoreSpec): { slug: string; dir: string; products: GeneratedProduct[]; files: StoreFile[] } {
  const brand = spec.brand.trim() || 'Northline';
  const niche = spec.niche.trim() || 'everyday goods';
  const slug = slugify(brand);
  const dir = `/home/harmos/HarmOS/workspace/stores/${slug}`;
  const products = productsFor({ ...spec, brand, niche });
  const toneLine = spec.tone === 'warm'
    ? 'Written like a person, not a billboard.'
    : spec.tone === 'technical'
      ? 'Specs first. Adjectives last.'
      : 'Short sentences. No invented superlatives.';

  const index = page(spec, brand, `
    <h1>${escapeHtml(brand)}</h1>
    <p>${escapeHtml(toneLine)} A draft catalog for <strong>${escapeHtml(niche)}</strong>. Replace every blurb with something you can defend.</p>
    ${products.map((p) => `<article class="card"><h2>${escapeHtml(p.name)}</h2><p>${escapeHtml(p.blurb)}</p><p class="price">$${p.price.toFixed(2)} <span class="note">SKU ${escapeHtml(p.sku)} · supplier lead ${p.leadDays} days (placeholder)</span></p></article>`).join('')}
  `);

  const product = page(spec, products[0].name, `
    <h1>${escapeHtml(products[0].name)}</h1>
    <p class="price">$${products[0].price.toFixed(2)}</p>
    <p>${escapeHtml(products[0].blurb)}</p>
    <div class="card"><h2>What this page will not do</h2>
    <ul><li>No “only 2 left” unless your inventory system says so.</li>
    <li>No star ratings until real orders exist.</li>
    <li>No checkout button that pretends to charge a card.</li></ul></div>
    <p class="note">Cost basis used for the draft margin: $${products[0].cost.toFixed(2)}. Confirm with a supplier invoice before you advertise the price.</p>
  `);

  const policies = page(spec, 'Policies', `
    <h1>Policies (draft)</h1>
    <div class="card"><h2>Shipping</h2><p>State the real carrier, the real window, and who pays for a supplier delay. Lead times in the catalog are placeholders.</p></div>
    <div class="card"><h2>Returns</h2><p>14-day draft window from delivery. Spell out who pays return freight. Dropshipped items that are personalized may be exempt only if you say so before purchase.</p></div>
    <div class="card"><h2>Privacy</h2><p>Collect only what fulfillment needs. Do not paste customer addresses into an AI prompt.</p></div>
  `);

  const dropship = page(spec, 'Fulfillment', `
    <h1>Dropshipping kit</h1>
    <p>This is an operations draft, not a supplier contract and not permission to resell goods you do not have the right to sell.</p>
    <div class="card"><h2>Before you list anything</h2>
    <ol>
      <li>Get a written wholesale or dropship agreement. Screenshot of a catalog is not an agreement.</li>
      <li>Order a sample. Photograph it yourself. Do not scrape another store's photos.</li>
      <li>Confirm the supplier will not include their marketing insert if you asked for a blind ship.</li>
      <li>Price after shipping, returns, fees, and the ${spec.marginPct}% draft margin — then decide if the price is honest.</li>
      <li>Register for sales tax where you have nexus. HarmOS will not file it for you.</li>
    </ol></div>
    <div class="card"><h2>Order path</h2>
    <p>Customer pays you → you pay supplier → supplier ships → you send tracking → you keep the ticket until the return window closes. If any step is manual, do not write “automated” on the site.</p></div>
  `);

  const csv = ['sku,name,price_usd,cost_usd,draft_margin_pct,lead_days,supplier,status',
    ...products.map((p) => `${p.sku},"${p.name.replace(/"/g, '')}",${p.price.toFixed(2)},${p.cost.toFixed(2)},${spec.marginPct},${p.leadDays},UNASSIGNED,draft`)].join('\n');

  const sop = `# ${brand} — fulfillment SOP (draft)

Niche: ${niche}
Generated by HarmOS Commerce Studio. Not legal advice. Not a live store.

## Roles
- You: listing, customer email, refunds, tax.
- Supplier: pick, pack, carrier. Named here only after you sign something: UNASSIGNED.

## When an order exists (it does not yet)
1. Match SKU to supplier SKU in \`sku-map.csv\`.
2. Pay the supplier from your account, not from a customer's card data.
3. Record tracking in the order ticket within one business day.
4. If the supplier misses the stated lead time, email the customer the same day. Do not invent a scan.

## What you will not automate
- Fake reviews, purchased followers, or countdown timers.
- Listing branded goods you are not authorized to resell.
- Charging a card from this HarmOS draft. No payment provider is connected.
`;

  const launch = `# Launch checklist — ${brand}

- [ ] Sample ordered and photographed by you
- [ ] Supplier agreement saved outside the chat log
- [ ] Prices checked against \`sku-map.csv\` after real shipping quotes
- [ ] Return policy matches what you can actually do
- [ ] Sales-tax question answered for your jurisdiction
- [ ] Domain and checkout belong to a real processor you configured yourself
- [ ] No scraped images, no invented testimonials

Until every box is checked, this folder is a draft in the Sovereign Vault, not a store.
`;

  const pricing = products.map((p) => {
    const fee = p.price * 0.029 + 0.3;
    const ship = 6.5;
    const profit = p.price - p.cost - fee - ship;
    return `- ${p.sku} ${p.name}: price $${p.price.toFixed(2)} − cost $${p.cost.toFixed(2)} − est. fee $${fee.toFixed(2)} − est. ship $${ship.toFixed(2)} = $${profit.toFixed(2)} before returns and ads`;
  }).join('\n');

  return {
    slug, dir, products,
    files: [
      { path: `${dir}/index.html`, content: index },
      { path: `${dir}/product.html`, content: product },
      { path: `${dir}/policies.html`, content: policies },
      { path: `${dir}/dropship.html`, content: dropship },
      { path: `${dir}/sku-map.csv`, content: csv + '\n' },
      { path: `${dir}/FULFILLMENT.md`, content: sop },
      { path: `${dir}/LAUNCH.md`, content: launch },
      { path: `${dir}/PRICING.md`, content: `# Draft unit economics — ${brand}\n\nEstimates only. Card fee assumed at 2.9% + $0.30. Shipping assumed at $6.50. Replace both before you advertise.\n\n${pricing}\n` },
    ],
  };
}
