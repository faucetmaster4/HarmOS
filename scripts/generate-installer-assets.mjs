/* Generates src/harmos/installerAssets.ts from real built artifacts on disk.
 * Never invents hashes or sizes: reads actual files and release/ova-manifest.json.
 */
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

const exePath = 'packaging/installer/HarmOS-Installer.exe';
const shPath  = 'packaging/installer/install-harmos.sh';
const cPath   = 'packaging/installer/harmos_installer.c';
const ovaMetaPath = 'release/ova-manifest.json';

const exeBuf = readFileSync(exePath);
const shBuf  = readFileSync(shPath);
const cBuf   = readFileSync(cPath);

let ovaMeta = {
  built: false,
  filename: 'HarmOS-0.1.0-x86_64.ova',
  path: 'release/HarmOS-0.1.0-x86_64.ova',
  sizeBytes: 0,
  sha256: '',
  vmdkName: 'HarmOS-0.1.0-x86_64-disk001.vmdk',
  vmdkSizeBytes: 0,
  virtualDiskGb: 30,
  guestOs: 'Ubuntu 24.04 LTS (Noble Numbat) x86_64',
  kernelVersion: '',
  builtAt: '',
  qemuBootVerified: false,
  smokeSummary: 'Pending OVA build.',
  smokeTranscript: '',
};

if (existsSync(ovaMetaPath)) {
  ovaMeta = { ...ovaMeta, ...JSON.parse(readFileSync(ovaMetaPath, 'utf8')) };
}

const out = `/* AUTO-GENERATED by scripts/generate-installer-assets.mjs — DO NOT EDIT MANUALLY */

export const INSTALLER_EXE = {
  filename: 'HarmOS-Installer.exe',
  format: 'PE32+ executable (console) x86-64, for MS Windows',
  sizeBytes: ${exeBuf.length},
  sha256: ${JSON.stringify(sha256(exeBuf))},
  base64: ${JSON.stringify(exeBuf.toString('base64'))},
} as const;

export const INSTALLER_SH = {
  filename: 'install-harmos.sh',
  sizeBytes: ${shBuf.length},
  sha256: ${JSON.stringify(sha256(shBuf))},
  source: ${JSON.stringify(shBuf.toString('utf8'))},
} as const;

export const INSTALLER_C_SOURCE = ${JSON.stringify(cBuf.toString('utf8'))};

export interface OvaReleaseManifest {
  built: boolean;
  filename: string;
  path: string;
  sizeBytes: number;
  sha256: string;
  vmdkName: string;
  vmdkSizeBytes: number;
  virtualDiskGb: number;
  guestOs: string;
  kernelVersion: string;
  builtAt: string;
  qemuBootVerified: boolean;
  smokeSummary: string;
  smokeTranscript: string;
}

export const OVA_MANIFEST: OvaReleaseManifest = ${JSON.stringify(ovaMeta, null, 2)};
`;

writeFileSync('src/harmos/installerAssets.ts', out);
console.log(`[assets] wrote src/harmos/installerAssets.ts (EXE=${exeBuf.length}B sha256=${sha256(exeBuf).slice(0, 12)}…, OVA built=${ovaMeta.built})`);
